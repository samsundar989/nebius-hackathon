#!/usr/bin/env python3
"""Devpost images (review #7 order 3), all 3:2 at 2x, rendered from site/ and docs/.

docs/devpost/render_assets.py -> docs/devpost/{thumbnail,1_first_screen,2_jq_refusal,3_funnel,
                                 4_planner,5_gate_matrix,6_review_findings,architecture}.png

Numbers on the images come from site/data (generated by scripts/readme_numbers.py), never typed.
Needs Playwright with Chromium in the Windows venv.
"""

from __future__ import annotations

import functools
import http.server
import sys
import threading
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "devpost"
VW, VH = 1200, 800  # CSS pixels; x2 device pixels -> 2400x1600

# Isolate one card at a stage width and zoom it to fill the 3:2 canvas: a narrower stage wraps the
# card taller, so short cards fill the height as well as the width.
ISOLATE = """([sel, width]) => {
  const el = document.querySelector(sel).cloneNode(true);
  el.querySelectorAll('details').forEach(d => d.open = true);
  const stage = document.createElement('div');
  stage.style.cssText = `width:${width}px;margin:0 auto;padding:8px 0`;
  stage.appendChild(el);
  document.body.replaceChildren(stage);
  document.body.style.cssText += ';min-height:100vh;display:flex;align-items:center';
  stage.style.zoom = Math.min(innerWidth * 0.96 / width, innerHeight * 0.96 / stage.offsetHeight);
}"""

# Image 6: the review-finding table from cases/open_bugs/REVIEW.md, as a dashboard-styled card.
FINDINGS = r"""(rows) => {
  const box = document.createElement('div'); box.id = 'findings'; box.className = 'panel';
  const cell = (s) => s.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>');
  box.innerHTML = `<h3>Wrong fixes a human review found on open bugs: caught by a machine check?</h3>
    <p class="muted">Every distinct verified diff, re-gated with inputs generated from the PoC (D-0078).</p>
    <table class="matrix"><tr>${rows[0].map((h) => `<th>${h}</th>`).join('')}</tr>
    ${rows.slice(1).map((r) => `<tr>${r.map((c) => `<td>${cell(c)}</td>`).join('')}</tr>`).join('')}</table>`;
  document.querySelector('main').append(box);
}"""


def findings_rows() -> list[list[str]]:
    text = (ROOT / "cases" / "open_bugs" / "REVIEW.md").read_text(encoding="utf-8")
    table = text.split("## Review finding", 1)[1].split("\n\n")[2]
    rows = [
        [c.strip().replace("`", "") for c in ln.strip("|").split("|")] for ln in table.splitlines()
    ]
    return [r for r in rows if not set("".join(r)) <= set("-")]


THUMB = """async () => {
  const n = await fetch('data/numbers.json').then(r => r.json());
  const r1 = n.arvo.p3_arvo27_r1;
  document.body.innerHTML = `<div style="height:100vh;display:flex;flex-direction:column;
    align-items:center;justify-content:center;background:#0f1115;color:#e8eaed;
    font-family:system-ui,'Segoe UI',sans-serif;text-align:center">
    <div style="font-size:120px;font-weight:700;letter-spacing:-0.02em">Leakproof</div>
    <div style="font-size:46px;color:#6fd39e;margin:10px 0 50px">Verified fixes, or nothing.</div>
    <div style="font-size:64px;font-weight:650">${r1.verified}/${r1.cases} real bugs verified
      · ${r1.strict} correct</div>
    <div style="font-size:30px;color:#a0a7b3;margin-top:28px">memory-safety repair for C, C++
      and CUDA · Nemotron on Nebius Token Factory</div></div>`;
}"""


def serve() -> tuple[http.server.ThreadingHTTPServer, int]:
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT))
    handler.log_message = lambda *a, **k: None  # type: ignore[method-assign]
    srv = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, srv.server_address[1]


def main() -> int:
    srv, port = serve()
    site = f"http://127.0.0.1:{port}/site/index.html"
    with sync_playwright() as p:
        browser = p.chromium.launch()
        ctx = browser.new_context(viewport={"width": VW, "height": VH}, device_scale_factor=2)
        page = ctx.new_page()

        def load() -> None:
            page.goto(site)
            page.wait_for_selector("#headline .stat")
            page.wait_for_selector("#cases button")
            page.wait_for_timeout(400)

        # First screen at a narrower viewport (bigger text), without the not-deployed note.
        page.set_viewport_size({"width": 960, "height": 640})
        load()
        page.evaluate(
            "document.querySelectorAll('.muted').forEach(e => "
            "{ if (e.textContent.includes('not deployed')) e.remove(); })"
        )
        page.screenshot(path=str(OUT / "1_first_screen.png"), scale="device")
        page.set_viewport_size({"width": VW, "height": VH})
        for name, sel, width in (("2_jq_refusal", "#refusal", 700), ("4_planner", "#planner", 540)):
            load()
            page.evaluate(ISOLATE, [sel, width])
            page.screenshot(path=str(OUT / f"{name}.png"))
        load()
        page.evaluate("document.querySelector('#funnel').closest('.panel').id = 'funnel-panel'")
        page.evaluate(ISOLATE, ["#funnel-panel", 600])
        page.screenshot(path=str(OUT / "3_funnel.png"))
        load()
        page.evaluate(
            "[...document.querySelectorAll('#cases button')]"
            ".find(b => b.textContent.includes('42531297')).click()"
        )
        page.wait_for_selector("#case .matrix")
        # The matrix with its case header above it; the advisory reviewer-notes column is dropped.
        page.evaluate(
            "() => { const panel = document.querySelector('#case .panel');"
            " const box = document.createElement('div'); box.id = 'matrix'; box.className = 'panel';"
            " box.append(panel.querySelector('.row').cloneNode(true),"
            " panel.querySelector('p.muted').cloneNode(true),"
            " document.querySelector('#case .matrix').closest('.scroll').cloneNode(true));"
            " box.querySelectorAll('tr').forEach(tr => tr.lastElementChild.remove());"
            " document.querySelector('main').append(box); }"
        )
        # Transposed (checks as rows, workers as columns) so it fills the 3:2 canvas.
        page.evaluate(
            "() => { const t = document.querySelector('#matrix table');"
            " const rows = [...t.rows].map(r => [...r.cells]);"
            " const out = document.createElement('table'); out.className = t.className;"
            " rows[0].forEach((_, j) => { const tr = out.insertRow();"
            " rows.forEach((r, i) => { const c = document.createElement(i && j ? 'td' : 'th');"
            " c.innerHTML = r[j].innerHTML; tr.append(c); }); });"
            " t.replaceWith(out); }"
        )
        page.evaluate(ISOLATE, ["#matrix", 640])
        page.screenshot(path=str(OUT / "5_gate_matrix.png"))
        load()
        page.evaluate(FINDINGS, findings_rows())
        page.evaluate(ISOLATE, ["#findings", 900])
        page.screenshot(path=str(OUT / "6_review_findings.png"))
        load()
        page.evaluate(THUMB)
        page.wait_for_timeout(300)
        page.screenshot(path=str(OUT / "thumbnail.png"))
        page.goto(f"http://127.0.0.1:{port}/docs/")
        page.set_content(
            "<body style='margin:0;background:#fff;display:flex;align-items:center;"
            "justify-content:center;height:100vh'>"
            f"<img src='http://127.0.0.1:{port}/docs/architecture.svg' style='width:96vw'></body>"
        )
        page.wait_for_timeout(500)
        page.screenshot(path=str(OUT / "architecture.png"))
        browser.close()
    srv.shutdown()
    for f in sorted(OUT.glob("*.png")):
        print(f.name, f.stat().st_size)
    return 0


if __name__ == "__main__":
    sys.exit(main())
