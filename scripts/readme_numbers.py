#!/usr/bin/env python3
"""Generate docs/NUMBERS.md: every results table the README quotes, from run records only.

scripts/readme_numbers.py        -> docs/NUMBERS.md (re-run whenever a run changes)
"""

from __future__ import annotations

import json
import sys
from collections import Counter

from leakproof.config import REPO_ROOT, RUNS_DIR

OUT = REPO_ROOT / "docs" / "NUMBERS.md"


def records(run: str) -> list[dict]:
    d = RUNS_DIR / run
    return [
        json.loads(p.read_text())
        for p in sorted(d.glob("*.json"))
        if p.name != "summary.json" and d.exists()
    ]


def funnel(run: str) -> dict | None:
    recs = records(run)
    if not recs:
        return None
    from leakproof.gate import Check, decide

    def v0(w: dict) -> bool:
        ch = (w.get("gate") or {}).get("checks") or {}
        keep = {
            k: Check(v["status"], v["detail"])
            for k, v in ch.items()
            if k not in ("differential", "refuzz", "safe_fix")
        }
        return bool(ch) and decide(keep) == "verified"

    raw = sum(
        any(
            ((w.get("gate") or {}).get("checks") or {}).get("patched", {}).get("status") == "pass"
            for w in r.get("workers", [])
        )
        for r in recs
    )
    usd = sum(r.get("usd", 0.0) for r in recs)
    ver = sum(r["verdict"] == "verified" for r in recs)
    return {
        "cases": len(recs),
        "raw": raw,
        "v0": sum(any(v0(w) for w in r.get("workers", [])) for r in recs),
        "verified": ver,
        "round1": sum(r.get("verdict_round1", r["verdict"]) == "verified" for r in recs),
        "round2": sum(r.get("verified_in_round") == 2 for r in recs),
        "usd": usd,
        "per_fix": usd / ver if ver else None,
        "verdicts": Counter(r["verdict"].split(":", 1)[0] for r in recs),
        "workers": Counter(w["status"] for r in recs for w in r.get("workers", [])),
    }


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "–"


def main() -> int:
    out = [
        "# Numbers",
        "",
        "Generated by `scripts/readme_numbers.py` from `runs/` — do not edit by hand.",
        "",
        "## ARVO: real OSS-Fuzz bugs, 27 calibrated cases",
        "",
        "| run | cases | crash gone (raw) | gate checks 1–4 (v0) | **verified (gate v1)** | "
        "verified in round 1 | added by repair round | model $ | $ / verified fix |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for run, label in (
        ("p3_arvo27_r1", "r1"),
        ("p3_arvo27_r2", "r2 (edit fallbacks + repair round)"),
    ):
        f = funnel(run)
        if f:
            out.append(
                f"| {label} | {f['cases']} | {f['raw']} ({pct(f['raw'], f['cases'])}) | {f['v0']} | "
                f"**{f['verified']} ({pct(f['verified'], f['cases'])})** | {f['round1']} | {f['round2']} | "
                f"${f['usd']:.4f} | ${f['per_fix']:.4f} |"
                if f["per_fix"]
                else f"| {label} | {f['cases']} | … |"
            )
    out += [
        "",
        "r1 as run counted 14 verified; jq 42531297 was rejected on a libFuzzer slow-unit artifact "
        "(D-0056) and is verified on re-judge, so r1 is 15/27.",
        "",
    ]
    for run, label in (("p3_arvo27_r1", "r1"), ("p3_arvo27_r2", "r2")):
        f = funnel(run)
        if f:
            out.append(
                f"- Worker outcomes {label}: "
                + ", ".join(f"{k} {v}" for k, v in f["workers"].most_common())
            )
    cal = RUNS_DIR / "p1_calibration_v3" / "summary.json"
    if cal.exists():
        c = json.loads(cal.read_text())
        a, r = c["adjudicated"], c["raw"]
        out += [
            "",
            "## Gate calibration: the developers' own fixes through the same gate",
            "",
            f"- Adjudicated: **{a['classes'].get('accepted', 0)}/{a['judged']} accepted**, "
            f"{a['classes'].get('true_reject', 0)} true reject (the developer fix leaks), "
            f"{a['classes'].get('false_reject', 0)} false rejects "
            f"({100 * (a['false_reject_rate'] or 0):.1f}%).",
            f"- Raw (before review): {r['classes'].get('accepted', 0)}/{r['judged']} accepted.",
            f"- Not countable: {', '.join(f'{k} {v}' for k, v in a['classes'].items() if k not in ('accepted', 'true_reject', 'false_reject'))}.",
        ]
    j = funnel("p4_juliet401x100_r1")
    if j:
        out += [
            "",
            "## Juliet (synthetic, NIST SARD)",
            "",
            f"- CWE-401 sample of 100: **{j['verified']}/100 verified** (every reproducible case; "
            f"{j['verdicts'].get('inconclusive', 0)} not reproducible), ${j['per_fix']:.4f} per verified fix.",
        ]
    s = funnel("e1_juliet60_v1")
    if s:
        out.append(f"- Smoke set of 60 (CWE-401/415/416): {s['verified']}/60 verified.")
    lb = RUNS_DIR / "leaderboard.json"
    if lb.exists():
        d = json.loads(lb.read_text())
        out += [
            "",
            f"## Planner leaderboard ({d['cases']} Juliet cases, repeated; workers 4 × Lightning)",
            "",
            "| planner | repeats | verified mean (min–max) | $ / verified fix | p50 latency |",
            "|---|---|---|---|---|",
        ]
        for k, v in d["configs"].items():
            out.append(
                f"| {k} | {v['repeats']} | {100 * v['verified_rate_mean']:.0f}% "
                f"({100 * v['verified_rate_min']:.0f}–{100 * v['verified_rate_max']:.0f}%) | "
                f"${v['usd_per_verified']} | {v['p50_latency_s']} s |"
            )
    rc = RUNS_DIR / "root_cause_accuracy_p3_arvo27_r1.json"
    if rc.exists():
        d = json.loads(rc.read_text())
        out += [
            "",
            "## Ultra's root cause vs the developer's fix (ARVO r1, a proxy)",
            "",
            f"- A hypothesis names a file the developer changed: {d['file_match']}/{d['cases']}.",
            f"- The root cause names a function the developer changed: "
            f"{d['function_match']}/{d['function_cases']} (lower bound: hunk headers name the "
            "function enclosing each change's first line).",
        ]
    cu = RUNS_DIR / "p5_cuda" / "verdicts.json"
    if cu.exists():
        d = json.loads(cu.read_text())
        cases = {k: v for k, v in d.items() if not k.startswith("_")}
        silenced = sum(
            r["verdict"] == "silenced_only" for v in cases.values() for r in v["candidates"]
        )
        out += [
            "",
            "## CUDA on a Kaggle T4 (compute-sanitizer)",
            "",
            f"- {sum(v['verdict'] == 'verified' for v in cases.values())}/{len(cases)} cases verified "
            f"({', '.join(f'{k}: {v["baseline_kind"]}' for k, v in cases.items())}); "
            f"{silenced} candidate(s) silenced the sanitizer but printed the wrong checksum.",
        ]
    led = RUNS_DIR / "cost_ledger.jsonl"
    if led.exists():
        usd = units = 0.0
        for line in led.read_text(encoding="utf-8").splitlines():
            try:
                e = json.loads(line)
            except ValueError:
                continue
            usd += float(e.get("usd", 0.0))
            units += float(e.get("units", 0.0))
        out += [
            "",
            "## Spend",
            "",
            f"- Every model call in the project, failed runs included: **${usd:.4f}** "
            "(Nebius billing agreed within $0.01 on 2026-10-24).",
            f"- Nebius Sandboxes: {units:.2f} units, not billed during the beta.",
        ]
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
